const assert=require('assert').strict;
const {randomUUID}=require('crypto');
module.exports=async(pool,{buyer,farmer,other},check)=>{
  process.env.DEMO_WALLETS_ENABLED='true';
  process.env.TELEBIRR_SIMULATION_ENABLED='true';
  const wallet=require('../src/modules/transactionsEscrow/wallet.service');
  const {createService}=require('../src/modules/telebirrSimulation/service');
  const s=createService({db:pool});
  const input=(amount='5000')=>({amount,confirm_demo:true,idempotency_key:randomUUID()});
  const reject=async(p,status,label)=>{await assert.rejects(p,{status});check(true,label);};
  for(const amount of ['0','-1','1.001','1e3',5,'1000001']) await reject(s.create(buyer,input(amount)),400,`simulation rejects invalid amount ${amount}`);
  await reject(s.create(farmer,input()),403,'farmer cannot create simulation');
  await reject(s.create(buyer,{...input(),confirm_demo:false}),400,'simulation disclosure confirmation required');
  const payload=input();
  const [p,q]=await Promise.all([s.create(buyer,payload),s.create(buyer,payload)]);
  check(p.payment_id===q.payment_id && p.status==='PENDING_AUTHORIZATION','concurrent create is durable and idempotent');
  await reject(s.create(buyer,{...payload,amount:'1'}),409,'creation key payload mismatch');
  await reject(s.get(other,p.payment_id),404,'ownership enforced on status');
  await reject(s.act(other,p.payment_id,'approve',input()),404,'ownership enforced on approval');
  await reject(s.act(buyer,p.payment_id,'approve',input('1')),409,'exact authorization amount required');
  check((await wallet.summary(buyer)).available==='0.00','pending payment cannot credit wallet');
  process.env.DEMO_WALLET_MAX_BALANCE='1';
  await reject(s.act(buyer,p.payment_id,'approve',payload),409,'credit failure rolls transaction back');
  check((await s.get(buyer,p.payment_id)).status==='PENDING_AUTHORIZATION','authorization rolls back with failed credit');
  check((await pool.query('SELECT count(*)::int AS n FROM telebirr_demo_audit WHERE payment_id=$1 AND status=\'AUTHORIZED\'',[p.payment_id])).rows[0].n===0,'rollback also removes authorization audit');
  delete process.env.DEMO_WALLET_MAX_BALANCE;
  const [approved,replayed]=await Promise.all([s.act(buyer,p.payment_id,'approve',payload),s.act(buyer,p.payment_id,'approve',payload)]);
  check(approved.status==='CREDITED' && approved.ledger_reference===replayed.ledger_reference,'concurrent approval creates at most one credit');
  check((await wallet.summary(buyer)).available==='5000.00','wallet receives exactly 5000 virtual ETB');
  const restarted=createService({db:pool});
  check((await restarted.get(buyer,p.payment_id)).ledger_reference===approved.ledger_reference,'restart and lost response status recovery persist');
  check((await restarted.act(buyer,p.payment_id,'approve',payload)).ledger_reference===approved.ledger_reference,'network retry returns same credit');
  await reject(s.act(buyer,p.payment_id,'decline'),409,'credited payment cannot be declined');
  await assert.rejects(pool.query("UPDATE telebirr_demo_payments SET status='PENDING_AUTHORIZATION',ledger_event_id=NULL,authorized_at=NULL WHERE payment_id=$1",[p.payment_id]));check(true,'database prevents terminal replay');
  await assert.rejects(pool.query('DELETE FROM telebirr_demo_audit WHERE payment_id=$1',[p.payment_id]));check(true,'audit is immutable');
  await assert.rejects(pool.query(`INSERT INTO demo_wallet_entries(wallet_id,event_type,amount_minor,idempotency_key)
    SELECT wallet_id,event_type,amount_minor,idempotency_key FROM demo_wallet_entries WHERE event_id=$1`,[approved.ledger_reference]));check(true,'database unique key prevents duplicate ledger credit');
  const history=await wallet.history(buyer);
  check(history.items.length===1 && history.items[0].simulation_reference===p.reference,'linked history labels simulation without double counting');
  check((await wallet.history(buyer,{funding_source:'instant'})).items.length===0 && (await wallet.history(buyer,{funding_source:'telebirr-demo'})).items.length===1,'read-only history separates instant and simulation credits');
  await reject(wallet.topUp(buyer,{...input('1'),idempotency_key:`telebirr-demo:${randomUUID()}`}),400,'instant top-up cannot use reserved simulation keys');
  const rateLimited=await s.create(buyer,input('1'));
  process.env.DEMO_WALLET_TOP_UPS_PER_HOUR='1';
  await reject(s.act(buyer,rateLimited.payment_id,'approve',input('1')),429,'simulation reuses authoritative wallet hourly credit limit');
  delete process.env.DEMO_WALLET_TOP_UPS_PER_HOUR;
  await s.act(buyer,rateLimited.payment_id,'cancel');
  const noCredit=await s.create(buyer,input('1'));
  await assert.rejects(pool.query("UPDATE telebirr_demo_payments SET status='AUTHORIZED',authorized_at=clock_timestamp() WHERE payment_id=$1",[noCredit.payment_id]));
  check((await s.get(buyer,noCredit.payment_id)).status==='PENDING_AUTHORIZATION','database cannot commit authorization without linked ledger credit');
  await s.act(buyer,noCredit.payment_id,'cancel');
  for(const action of ['decline','cancel']) {
    const d=await s.create(buyer,input('1'));
    const terminal=await s.act(buyer,d.payment_id,action);
    check(terminal.status===(action==='decline'?'DECLINED':'CANCELLED'),'valid '+action);
    await reject(s.act(buyer,d.payment_id,'approve',input('1')),409,action+' cannot later credit');
  }
  process.env.TELEBIRR_SIMULATION_EXPIRY_SECONDS='1';
  const exp=await s.create(buyer,input('1'));
  await pool.query('SELECT pg_sleep(1.1)');
  const expiredRace=await Promise.all([s.get(buyer,exp.payment_id),s.act(buyer,exp.payment_id,'approve',input('1'))]);
  check(expiredRace.every(p=>p.status==='EXPIRED'),'concurrent expiry and authorization never credits');
  delete process.env.TELEBIRR_SIMULATION_EXPIRY_SECONDS;
  for(const flag of ['TELEBIRR_SIMULATION_ENABLED','DEMO_WALLETS_ENABLED','SIMULATED_PAYMENTS_ENABLED']) {
    process.env[flag]='false';await reject(s.create(buyer,input()),503,flag+' gate enforced');process.env[flag]='true';
  }
  process.env.NODE_ENV='production';
  await reject(s.act(buyer,p.payment_id,'approve',payload),503,'production cannot credit even with flags true');
  process.env.NODE_ENV='test';
  process.env.TELEBIRR_SIMULATION_EXPIRY_SECONDS='NaN';
  await reject(s.create(buyer,input()),503,'invalid expiry configuration rejected');
  delete process.env.TELEBIRR_SIMULATION_EXPIRY_SECONDS;
  check((await pool.query('SELECT count(*)::int AS n FROM telebirr_uat_funding')).rows[0].n===0,'official UAT records unaffected');
  const audit=await wallet.admin({});
  check(audit.conservation.balanced && !audit.mismatches.length,'simulation uses existing ledger conservation');
  check((await wallet.summary(buyer)).available==='5000.00','declines, cancellations, expiry and replay do not change balance');
  // Spend the actual simulation credit through unchanged marketplace workflows.
  const listings=require('../src/modules/listings/listing.service');
  const escrow=require('../src/modules/transactionsEscrow/simulation.service');
  const listing=await listings.createListing({crop_type:'Simulation-funded produce',variety:'White',quantity:'1',unit:'quintal',price_per_unit:'100',quality_grade:'A',location_lat:9.03,location_lng:38.74,client_id:randomUUID(),operation_id:randomUUID()},farmer);
  const t=await escrow.create({buyer_id:buyer,listing_id:listing.listing_id,quantity:'1',payment_method:'demo_wallet',request_id:randomUUID()});
  await escrow.pay(t.transaction_id,buyer,{method:'demo_wallet',confirm_demo:true,idempotency_key:randomUUID()});
  check((await wallet.summary(buyer)).available==='4900.00','simulation-funded purchase debits virtual wallet through existing escrow');
  const details=await escrow.details(t.transaction_id,buyer), allocation=details.allocations[0].allocation_id;
  check(details.balances.held==='100.00','simulation-funded purchase creates exact escrow hold');
  await escrow.ready(t.transaction_id,allocation,farmer);
  const qr=await escrow.issueQr(t.transaction_id,allocation,farmer);
  await escrow.verifyQr(t.transaction_id,allocation,buyer,{qr_token:qr.qr_token,confirm_delivery:true});
  await escrow.settle(t.transaction_id,allocation,farmer);
  check((await escrow.details(t.transaction_id,buyer)).balances.settled==='100.00','QR delivery settles simulation-funded purchase');
  check((await wallet.admin({})).conservation.balanced,'conservation holds after spending simulation credit and farmer settlement');
};
