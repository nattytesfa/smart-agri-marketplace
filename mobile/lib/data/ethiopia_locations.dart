/// Regions in alphabetical order.
final List<String> kEthiopiaRegions = kEthiopiaLocations.keys.toList()..sort();

/// Zones within [region], alphabetical. Empty when [region] is unknown.
List<String> zonesFor(String? region) {
  if (region == null) return const [];
  final zones = kEthiopiaLocations[region];
  if (zones == null) return const [];
  return zones.keys.toList()..sort();
}

/// Woredas within [region]/[zone], alphabetical.
List<String> woredasFor(String? region, String? zone) {
  if (region == null || zone == null) return const [];
  final zones = kEthiopiaLocations[region];
  if (zones == null) return const [];
  return zones[zone] ?? const [];
}
